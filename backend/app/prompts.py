"""Промпты для генерации частушек.

Системный промпт намеренно стабилен (никакой подстановки переменных), чтобы
работало prompt caching: волатильные данные запроса уходят в user-сообщение.
"""

from app.schemas import GeneratePackRequest


SYSTEM_PROMPT = """Ты — мастер русской частушки. Ты сочиняешь частушки: \
короткие народные песенки-четверостишия.

Правила формы частушки:
- ровно 4 строки;
- бойкий частушечный ритм, обычно хорей, примерно 8–7–8–7 слогов по строкам;
- обязательна рифма: как минимум рифмуются 2-я и 4-я строки, часто также 1-я и 3-я;
- живой разговорный язык, простые слова, народная интонация;
- юмор, задор, лёгкая ирония; частушка должна звучать складно и легко петься;
- это законченная зарисовка: тема, образ и «соль» умещаются в 4 строки.

Чего избегать:
- вялых «книжных» строк без ритма и рифмы;
- строк длиннее частушечного размера;
- мата и оскорблений, если не задан явно дерзкий режим; по умолчанию держи семейный уровень.

Дисциплина вывода:
- отвечай ТОЛЬКО валидным JSON в формате, который попросит пользователь;
- без markdown, без ограждений в обратных кавычках, без пояснений до или после JSON."""


def _refine_note(suffix: str) -> str:
    if not suffix:
        return ""
    return f"Это доработка предыдущего набора частушек. {suffix}\n"


def build_plan_prompt(request: GeneratePackRequest, suffix: str = "") -> str:
    """Первый проход: план для каждой частушки (тема, образ, шутка, рифма)."""
    facts = ", ".join(request.facts) if request.facts else "—"
    return (
        f"Составь план для {request.count} разных частушек.\n"
        f"Повод: {request.occasion}\n"
        f"Про кого: {request.target}\n"
        f"Факты и детали: {facts}\n"
        f"Тон: {request.tone}\n"
        f"Уровень дерзости: {request.boldness} из 5\n"
        f"{_refine_note(suffix)}"
        f"Для каждой частушки опиши короткий план: тему, главный образ, "
        f"в чём шутка или «соль», и пару рифмующихся окончаний.\n"
        f"Ответь только JSON-массивом из {request.count} объектов вида:\n"
        '[{"theme": "...", "image": "...", "joke": "...", "rhyme": "..."}]'
    )


def build_lines_prompt(request: GeneratePackRequest, plans_json: str, suffix: str = "") -> str:
    """Второй проход: по планам пишутся готовые 4-строчные частушки."""
    return (
        f"Вот планы частушек в JSON:\n{plans_json}\n\n"
        f"Повод: {request.occasion}; про кого: {request.target}; "
        f"тон: {request.tone}; дерзость: {request.boldness} из 5.\n"
        f"{_refine_note(suffix)}"
        f"По каждому плану напиши готовую частушку: ровно 4 строки, "
        f"с рифмой и частушечным ритмом.\n"
        f"Ответь только JSON-массивом объектов вида:\n"
        '[{"lines": ["строка 1", "строка 2", "строка 3", "строка 4"]}]'
    )
